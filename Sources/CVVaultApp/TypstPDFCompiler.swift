import Foundation

enum TypstPDFCompiler {
    static let installationURL = URL(string: "https://typst.app/open-source/#download")!

    static func executable() -> URL? {
        let home = FileManager.default.homeDirectoryForCurrentUser.path
        let common = ["/opt/homebrew/bin", "/usr/local/bin", "/opt/local/bin", "\(home)/.cargo/bin", "\(home)/.local/bin"]
        let path = (ProcessInfo.processInfo.environment["PATH"] ?? "")
            .split(separator: ":")
            .filter { $0.hasPrefix("/") }
            .map(String.init)
        return (common + path).lazy
            .map { URL(fileURLWithPath: $0, isDirectory: true).appendingPathComponent("typst") }
            .first { candidate in
                let resolved = candidate.resolvingSymlinksInPath()
                return (try? resolved.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile) == true
                    && FileManager.default.isExecutableFile(atPath: resolved.path)
            }
    }

    /// Compiles only the source generated by CVExporter. The PDF is read into memory.
    static func compile(_ typst: String) throws -> Data {
        guard let executable = executable() else { throw Failure.unavailable }
        let manager = FileManager.default
        let workspace = manager.temporaryDirectory.appendingPathComponent("CVVault-\(UUID())", isDirectory: true)
        try manager.createDirectory(at: workspace, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
        defer { try? manager.removeItem(at: workspace) }

        // Unlink the input before launching Typst. Its file handle remains readable on stdin.
        let source = workspace.appendingPathComponent("input.typ")
        try Data(typst.utf8).write(to: source, options: .withoutOverwriting)
        let input = try FileHandle(forReadingFrom: source)
        defer { try? input.close() }
        try manager.removeItem(at: source)

        let output = Pipe()
        let process = Process()
        process.executableURL = executable
        process.currentDirectoryURL = workspace
        process.arguments = ["compile", "--root", workspace.path, "--format", "pdf", "-", "-"]
        process.environment = ProcessInfo.processInfo.environment.filter { !$0.key.hasPrefix("TYPST_") }
        process.standardInput = input
        process.standardOutput = output
        process.standardError = FileHandle.nullDevice
        do {
            try process.run()
        } catch {
            throw Failure.compilation
        }

        let pdf = output.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        guard process.terminationStatus == 0, pdf.starts(with: Data("%PDF-".utf8)) else {
            throw Failure.compilation
        }
        return pdf
    }

    enum Failure: LocalizedError {
        case unavailable
        case compilation
        case emptyPDF

        var errorDescription: String? {
            switch self {
            case .unavailable:
                "Installez Typst sur ce Mac pour créer un PDF."
            case .compilation:
                "Typst n’a pas pu produire le PDF. Vérifiez que votre compilateur est à jour."
            case .emptyPDF:
                "Le PDF généré ne contient aucune page lisible."
            }
        }
    }
}
